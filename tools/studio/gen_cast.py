#!/usr/bin/env python3
"""STU-N2: write studio/workflows/vn-cast-<N>/{graph.json,workflow.toml} for N = 2..4 people.

One scene prompt over the whole picture plus one text encode per person limited to a vertical strip
(ConditioningSetAreaPercentage), all joined with ConditioningCombine. The strips overlap by OVERLAP of the width
so the seams blend. Run from the repo root: python3 tools/studio/gen_cast.py
"""

import json
import os

OVERLAP = 0.07
PX = {3: (1536, 768), 4: (1664, 768)}  # more people need a wider picture or the third face goes missing
PREFIX = "masterpiece, best quality, amazing quality, very aesthetic, absurdres, newest, {rating}, adult, mature"
SLOT_PREFIX = "adult, mature, "
NEG = (
    "worst quality, bad quality, low quality, lowres, blurry, jpeg artifacts, watermark, signature, text, logo, "
    "bad anatomy, bad hands, extra fingers, missing fingers, fused fingers, extra limbs, deformed, disfigured, "
    "mutated, cropped head, extra hands, extra arms, malformed hands, vertical lines, streaks, scan lines, "
    "lined paper, child, loli, shota, underage, young child, kid, toddler, teen, minor, childlike body, "
    "{rating_neg}{value}"
)
# Three or more people need framing words (2 people did fine without; with them bystanders appeared).
FRAMING = {n: f"{n}people, group shot, medium shot, everyone in frame, " for n in (3, 4)}
NEG_CROWD = {n: "crowd, extra people, background characters, " for n in (3, 4)}
DEFAULT_CAST = [
    "1girl, long red hair, green eyes, blue school uniform, smiling",
    "1boy, short black hair, brown eyes, white shirt, black jacket",
    "1girl, short blonde hair, purple eyes, yellow sundress",
    "1boy, silver hair, blue eyes, red coat",
]


def strips(n):
    """(x, width) of each person's strip as fractions of the picture width."""
    w = (1 + (n - 1) * OVERLAP) / n
    return [(round(i * (w - OVERLAP), 4), round(w, 4)) for i in range(n)]


def graph(n):
    g = {
        "1": {"class_type": "CheckpointLoaderSimple", "inputs": {"ckpt_name": "novaAnimeXL_ilV170.safetensors"}},
        "3": {"class_type": "CLIPSetLastLayer", "inputs": {"clip": ["1", 1], "stop_at_clip_layer": -2}},
        "4": {"class_type": "CLIPTextEncode", "inputs": {"clip": ["3", 0], "text": ""}},
        "5": {"class_type": "CLIPTextEncode", "inputs": {"clip": ["3", 0], "text": ""}},
        "6": {"class_type": "EmptyLatentImage", "inputs": {"width": PX.get(n, (1216, 832))[0], "height": PX.get(n, (1216, 832))[1], "batch_size": 1}},
    }
    prev = ["4", 0]
    for i, (x, w) in enumerate(strips(n), start=1):
        enc, area, comb = str(30 + i), str(40 + i), str(50 + i)
        g[enc] = {"class_type": "CLIPTextEncode", "inputs": {"clip": ["3", 0], "text": ""}}
        g[area] = {
            "class_type": "ConditioningSetAreaPercentage",
            "inputs": {"conditioning": [enc, 0], "width": w, "height": 1.0, "x": x, "y": 0.0, "strength": 1.0},
        }
        g[comb] = {
            "class_type": "ConditioningCombine",
            "inputs": {"conditioning_1": prev, "conditioning_2": [area, 0]},
        }
        prev = [comb, 0]
    pos = prev
    g["7"] = {
        "class_type": "KSampler",
        "inputs": {
            "model": ["1", 0], "positive": pos, "negative": ["5", 0], "latent_image": ["6", 0], "seed": 42,
            "steps": 28, "cfg": 5.5, "sampler_name": "euler_ancestral", "scheduler": "normal", "denoise": 1,
        },
    }  # fmt: skip
    tile = {"tile_size": 512, "overlap": 64, "temporal_size": 64, "temporal_overlap": 8}
    g["50"] = {"class_type": "VAEDecodeTiled", "inputs": {"samples": ["7", 0], "vae": ["1", 2], **tile}}
    g["60"] = {"class_type": "ImageScaleBy", "inputs": {"image": ["50", 0], "upscale_method": "lanczos", "scale_by": 1.5}}
    g["61"] = {"class_type": "VAEEncodeTiled", "inputs": {"pixels": ["60", 0], "vae": ["1", 2], **tile}}
    g["62"] = {
        "class_type": "KSampler",
        "inputs": {
            "model": ["1", 0], "positive": pos, "negative": ["5", 0], "latent_image": ["61", 0], "seed": 43,
            "steps": 18, "cfg": 5.5, "sampler_name": "euler_ancestral", "scheduler": "normal", "denoise": 0.35,
        },
    }  # fmt: skip
    g["63"] = {"class_type": "VAEDecodeTiled", "inputs": {"samples": ["62", 0], "vae": ["1", 2], **tile}}
    g["20"] = {
        "class_type": "SaveImage",
        "inputs": {"images": ["63", 0], "filename_prefix": f"kompanion/vn-cast-{n}"},
    }
    return g


def toml(n):
    lines = [
        f"# STU-N2: VN scene with {n} named people, each in their own strip of the picture (generated by tools/studio/gen_cast.py).",
        f'title = "VN scene, {n} people"',
        f'description = "A visual novel CG with {n} characters; every character has their own prompt and place, so hair and clothes stay with the right person."',
        'graph = "graph.json"',
        'outputs = ["20"]',
        'machines = ["soucouyant"]',
        "vram_mb = 10000",
        "ram_mb = 10000",
        "",
        "[studio]",
        f'label = "VN scene, {n} people"',
        f'hint = "{n} characters side by side, each with their own look"',
        'sizes = ["wide"]',
        f"order = {20 + n}",
        f"cast = {n}",
        f"px = {{ wide = [{PX.get(n, (1216, 832))[0]}, {PX.get(n, (1216, 832))[1]}] }}",
        "",
        "[[param]]",
        'name = "prompt"',
        'type = "string"',
        'default = "a school rooftop at sunset, wind in their hair"',
        'node = "4"',
        'input = "text"',
        f'template = "{PREFIX}, {FRAMING.get(n, "")}visual novel cg, detailed background, cinematic lighting, {{value}}"',
        "",
        "[[param]]",
        'name = "negative"',
        'type = "string"',
        'default = ""',
        'node = "5"',
        'input = "text"',
        f'template = "{NEG_CROWD.get(n, "")}{NEG}"',
        "",
    ]
    px = PX.get(n, (1216, 832))
    for name, d in (("width", px[0]), ("height", px[1])):
        lines += [
            "[[param]]", f'name = "{name}"', 'type = "int"', f"default = {d}", "min = 512", "max = 2048",
            'node = "6"', f'input = "{name}"', "",
        ]  # fmt: skip
    lines += [
        "[[param]]", 'name = "seed"', 'type = "seed"', "default = -1", 'node = "7"', 'input = "seed"',
        'also = [{ node = "62", input = "seed", add = 1 }]', "",
        "[[param]]", 'name = "rating"', 'type = "choice"', 'default = "general"',
        'choices = ["general", "sensitive", "questionable", "explicit"]', 'adult = ["questionable", "explicit"]',
        'words = { rating_neg = { general = "nsfw, nude, explicit, " } }', "",
    ]  # fmt: skip
    for i, (x, w) in enumerate(strips(n), start=1):
        lines += [
            "[[param]]", f'name = "person{i}"', 'type = "string"', f'default = "{DEFAULT_CAST[i - 1]}"',
            f'node = "{30 + i}"', 'input = "text"', f'template = "{SLOT_PREFIX}solo, {{value}}"', "",
            "[[param]]", f'name = "person{i}_x"', 'type = "float"', f"default = {x}", "min = 0", "max = 1",
            f'node = "{40 + i}"', 'input = "x"', "",
            "[[param]]", f'name = "person{i}_width"', 'type = "float"', f"default = {w}", "min = 0.2", "max = 1",
            f'node = "{40 + i}"', 'input = "width"', "",
        ]  # fmt: skip
    lines += [
        "[[model]]", 'file = "novaAnimeXL_ilV170.safetensors"', 'licence = "Fair AI Public License 1.0-SD"', "",
    ]  # fmt: skip
    return "\n".join(lines)


def main():
    for n in (2, 3, 4):
        d = os.path.join("studio", "workflows", f"vn-cast-{n}")
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, "graph.json"), "w", encoding="utf-8") as f:
            json.dump(graph(n), f, indent=1)
            f.write("\n")
        with open(os.path.join(d, "workflow.toml"), "w", encoding="utf-8") as f:
            f.write(toml(n))


if __name__ == "__main__":
    main()
