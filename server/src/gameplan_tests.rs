#[test]
fn missing_fields_are_named() {
    // an asset task without its kind
    let text = r#"{"title":"T","goal":"G","code_tasks":[],"asset_tasks":[{"key":"hero","title":"Knight","workflow":"sprite"}]}"#;
    let err = parse(text).unwrap_err();
    assert!(err.starts_with("The answer is not a game plan"), "{err}");
    assert!(err.contains("kind"), "{err}");
    // no code_tasks at all
    let err = parse(r#"{"title":"T","goal":"G","asset_tasks":[]}"#).unwrap_err();
    assert!(err.contains("code_tasks"), "{err}");
}

#[test]
fn optional_asset_fields_default() {
    let text = r#"{"title":"T","goal":"G","code_tasks":[],"asset_tasks":[{"key":"hero","title":"Knight","kind":"sprite","workflow":"sprite"}]}"#;
    let p = parse(text).unwrap();
    let a = &p.asset_tasks[0];
    assert!(a.library_id.is_none() && a.params.is_empty() && a.tags.is_empty() && a.depends_on.is_empty() && a.needed_by.is_empty());
}

#[test]
fn kinds_map_to_workflow_outputs() {
    for (kind, out) in [("sprite", "image"), ("image", "image"), ("tileset", "image"), ("background", "image"), ("audio", "audio"), ("music", "audio"), ("sfx", "audio"), ("video", "video"), ("model", "model")] {
        assert_eq!(output_of_kind(kind), Some(out), "{kind}");
    }
    assert_eq!(output_of_kind("hologram"), None);
    assert_eq!(output_of_kind("Sprite"), Some("image"), "case does not matter");
}

#[test]
fn one_parameter_value_is_judged_against_its_definition() {
    let steps = WfParam { name: "steps".into(), kind: "number".into(), choices: vec![], min: Some(1.0), max: Some(60.0) };
    assert!(param_issue(&steps, &json!(30)).is_none());
    assert!(param_issue(&steps, &json!(1)).is_none() && param_issue(&steps, &json!(60)).is_none(), "limits are allowed");
    assert!(param_issue(&steps, &json!(0)).unwrap().contains("steps"));
    assert!(param_issue(&steps, &json!(61)).is_some());
    assert!(param_issue(&steps, &json!("many")).is_some());
    let size = WfParam { name: "size".into(), kind: "choice".into(), choices: vec!["square".into(), "tall".into()], min: None, max: None };
    assert!(param_issue(&size, &json!("tall")).is_none());
    assert!(param_issue(&size, &json!("huge")).unwrap().contains("huge"));
    assert!(param_issue(&size, &json!(3)).is_some());
    let prompt = WfParam { name: "prompt".into(), kind: "text".into(), choices: vec![], min: None, max: None };
    assert!(param_issue(&prompt, &json!("a gold coin")).is_none());
    assert!(param_issue(&prompt, &json!(7)).is_some());
}

#[test]
fn an_asset_needs_exactly_one_source() {
    let none = with_asset(|a| a.workflow = None);
    assert_eq!(kinds(&asset_issues(&none, &library(), &workflows())), vec!["no_source"]);
    let two = with_asset(|a| a.library_id = Some("a07".into()));
    assert_eq!(kinds(&asset_issues(&two, &library(), &workflows())), vec!["two_sources"]);
}

#[test]
fn a_library_asset_must_exist_and_match_the_kind() {
    let missing = with_asset(|a| {
        a.workflow = None;
        a.params.clear();
        a.library_id = Some("zz99".into());
    });
    assert_eq!(kinds(&asset_issues(&missing, &library(), &workflows())), vec!["unknown_asset"]);
    let wrong = with_asset(|a| {
        a.workflow = None;
        a.params.clear();
        a.library_id = Some("b01".into());
    });
    assert_eq!(kinds(&asset_issues(&wrong, &library(), &workflows())), vec!["wrong_kind"]);
}

#[test]
fn an_impossible_workflow_is_flagged() {
    let unknown = with_asset(|a| a.workflow = Some("sprite-xl".into()));
    assert_eq!(kinds(&asset_issues(&unknown, &library(), &workflows())), vec!["unknown_workflow"]);
    // an audio workflow cannot make a sprite
    let audio = with_asset(|a| {
        a.workflow = Some("moss-sfx".into());
        a.params.clear();
    });
    assert_eq!(kinds(&asset_issues(&audio, &library(), &workflows())), vec!["wrong_output"]);
    let kind = with_asset(|a| a.kind = "hologram".into());
    assert_eq!(kinds(&asset_issues(&kind, &library(), &workflows())), vec!["unknown_kind"]);
}

#[test]
fn parameters_are_checked_against_the_workflow() {
    let unknown = with_asset(|a| {
        a.params.insert("glow".into(), json!(1));
    });
    assert_eq!(kinds(&asset_issues(&unknown, &library(), &workflows())), vec!["unknown_param"]);
    let range = with_asset(|a| {
        a.params.insert("steps".into(), json!(200));
    });
    assert_eq!(kinds(&asset_issues(&range, &library(), &workflows())), vec!["bad_param"]);
    let choice = with_asset(|a| {
        a.params.insert("size".into(), json!("huge"));
    });
    assert_eq!(kinds(&asset_issues(&choice, &library(), &workflows())), vec!["bad_param"]);
    let not_number = with_asset(|a| {
        a.params.insert("steps".into(), json!("many"));
    });
    assert_eq!(kinds(&asset_issues(&not_number, &library(), &workflows())), vec!["bad_param"]);
}

#[test]
fn library_assets_are_preferred_over_generating() {
    let mut p = with_asset(|a| {
        a.kind = "sprite".into();
        a.tags = vec!["Knight".into(), "run".into()];
        a.params.clear();
    });
    assert_eq!(prefer_library(&mut p, &library()), vec!["coin_art".to_string()]);
    let a = &p.asset_tasks[1];
    assert_eq!(a.library_id.as_deref(), Some("a07"), "a07 shares knight and run, a12 only knight");
    assert!(a.workflow.is_none() && a.params.is_empty());
    assert!(asset_issues(&p, &library(), &workflows()).is_empty());
}

#[test]
fn nothing_is_swapped_without_a_match() {
    let mut p = good();
    assert!(prefer_library(&mut p, &library()).is_empty(), "coin has no library match, hero already uses the library");
    assert_eq!(p, good());
    // same tags but another kind
    let mut p = with_asset(|a| {
        a.kind = "audio".into();
        a.tags = vec!["knight".into()];
    });
    assert!(prefer_library(&mut p, &library()).is_empty());
    assert_eq!(p.asset_tasks[1].workflow.as_deref(), Some("sprite"));
}

#[test]
fn a_game_plan_maps_onto_a_task_plan() {
    let plan = to_plan(&good());
    assert_eq!(plan.title, "Tiny platformer");
    assert_eq!(plan.milestones.len(), 2);
    assert_eq!(plan.milestones[0].title, "Assets");
    assert_eq!(plan.milestones[1].title, "Code");
    let assets = &plan.milestones[0].tasks;
    assert_eq!(assets.iter().map(|t| t.key.as_str()).collect::<Vec<_>>(), vec!["hero", "coin_art"]);
    assert!(assets[0].goal.contains("a12"), "{}", assets[0].goal);
    assert!(assets[1].goal.contains("sprite") && assets[1].goal.contains("a gold coin"), "{}", assets[1].goal);
    assert!(!assets[1].done_when.trim().is_empty());
    let code = &plan.milestones[1].tasks;
    assert_eq!(code[0].depends_on, vec!["hero".to_string()]);
    assert_eq!(code[1].depends_on, vec!["coin_art".to_string(), "player".to_string()]);
    assert!(crate::planner::issues(&plan, &Limits::default()).is_empty());
}

#[test]
fn an_empty_side_gives_no_empty_milestone() {
    let mut p = good();
    p.asset_tasks.clear();
    let plan = to_plan(&p);
    assert_eq!(plan.milestones.len(), 1);
    assert_eq!(plan.milestones[0].title, "Code");
    let mut p = good();
    p.code_tasks.clear();
    for a in &mut p.asset_tasks {
        a.needed_by.clear();
    }
    assert_eq!(to_plan(&p).milestones.len(), 1);
}

#[test]
fn all_issues_joins_task_rules_and_asset_rules() {
    let mut p = with_asset(|a| a.workflow = Some("moss-sfx".into()));
    p.code_tasks[0].lines = 900;
    p.asset_tasks[0].needed_by = vec!["nobody".into()];
    let found = all_issues(&p, &Limits::default(), &library(), &workflows());
    let k = kinds(&found);
    assert!(k.contains(&"oversize".to_string()), "{k:?}");
    assert!(k.contains(&"wrong_output".to_string()), "{k:?}");
    assert!(k.contains(&"unknown_need".to_string()), "{k:?}");
}

fn ask_with(answers: Vec<&'static str>) -> (std::sync::Arc<std::sync::Mutex<Vec<Vec<serde_json::Value>>>>, impl FnMut(Vec<serde_json::Value>) -> std::future::Ready<Result<String, String>>) {
    let seen = std::sync::Arc::new(std::sync::Mutex::new(Vec::new()));
    let log = seen.clone();
    let mut left = answers.into_iter();
    (seen, move |messages| {
        log.lock().unwrap().push(messages);
        std::future::ready(left.next().map(String::from).ok_or_else(|| "no more answers".to_string()))
    })
}

#[tokio::test]
async fn the_model_is_asked_again_until_the_plan_is_valid() {
    let bad = bad_answer();
    let (seen, ask) = ask_with(vec!["Sure, here you go!", bad, GOOD]);
    let (plan, left) = generate(ask, "system", "make a platformer", &Limits::default(), &library(), &workflows()).await.unwrap();
    assert!(left.is_empty(), "{left:?}");
    assert_eq!(plan, good());
    let seen = seen.lock().unwrap();
    assert_eq!(seen.len(), 3);
    let last_user = |round: usize| seen[round].last().unwrap()["content"].as_str().unwrap().to_string();
    assert!(last_user(1).contains("no JSON"), "{}", last_user(1));
    assert!(last_user(2).contains("wrong_output"), "{}", last_user(2));
}

#[tokio::test]
async fn after_three_bad_rounds_the_last_plan_comes_back_with_its_issues() {
    let bad = bad_answer();
    let (_, ask) = ask_with(vec![bad, bad, bad]);
    let (plan, left) = generate(ask, "s", "u", &Limits::default(), &library(), &workflows()).await.unwrap();
    assert_eq!(plan.asset_tasks[1].workflow.as_deref(), Some("moss-sfx"));
    assert_eq!(kinds(&left), vec!["wrong_output"]);
}

