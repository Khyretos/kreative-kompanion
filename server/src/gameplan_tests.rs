fn ask_with(answers: Vec<&'static str>) -> (std::sync::Arc<std::sync::Mutex<Vec<Vec<serde_json::Value>>>>, impl FnMut(Vec<serde_json::Value>) -> std::future::Ready<Result<String, String>>) {
    let seen = std::sync::Arc::new(std::sync::Mutex::new(Vec::new()));
    let log = seen.clone();
    let mut left = answers.into_iter();
    (seen, move |messages| {
        log.lock().unwrap().push(messages);
        std::future::ready(left.next().map(String::from).ok_or_else(|| "no more answers".to_string()))
    })
}

#[tokio::test]
async fn the_model_is_asked_again_until_the_plan_is_valid() {
    let bad = bad_answer();
    let (seen, ask) = ask_with(vec!["Sure, here you go!", bad, GOOD]);
    let (plan, left) = generate(ask, "system", "make a platformer", &Limits::default(), &library(), &workflows()).await.unwrap();
    assert!(left.is_empty(), "{left:?}");
    assert_eq!(plan, good());
    let seen = seen.lock().unwrap();
    assert_eq!(seen.len(), 3);
    let last_user = |round: usize| seen[round].last().unwrap()["content"].as_str().unwrap().to_string();
    assert!(last_user(1).contains("no JSON"), "{}", last_user(1));
    assert!(last_user(2).contains("wrong_output"), "{}", last_user(2));
}

