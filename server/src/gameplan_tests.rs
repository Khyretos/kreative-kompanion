#[test]
fn one_parameter_value_is_judged_against_its_definition() {
    let steps = WfParam { name: "steps".into(), kind: "number".into(), choices: vec![], min: Some(1.0), max: Some(60.0) };
    assert!(param_issue(&steps, &json!(30)).is_none());
    assert!(param_issue(&steps, &json!(1)).is_none() && param_issue(&steps, &json!(60)).is_none(), "limits are allowed");
    assert!(param_issue(&steps, &json!(0)).unwrap().contains("steps"));
    assert!(param_issue(&steps, &json!(61)).is_some());
    assert!(param_issue(&steps, &json!("many")).is_some());
    let size = WfParam { name: "size".into(), kind: "choice".into(), choices: vec!["square".into(), "tall".into()], min: None, max: None };
    assert!(param_issue(&size, &json!("tall")).is_none());
    assert!(param_issue(&size, &json!("huge")).unwrap().contains("huge"));
    assert!(param_issue(&size, &json!(3)).is_some());
    let prompt = WfParam { name: "prompt".into(), kind: "text".into(), choices: vec![], min: None, max: None };
    assert!(param_issue(&prompt, &json!("a gold coin")).is_none());
    assert!(param_issue(&prompt, &json!(7)).is_some());
}

