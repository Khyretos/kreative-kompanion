#[tokio::test]
async fn library_assets_are_swapped_in_before_the_checks() {
    // the model generated the knight sprite although the library has it
    let text = GOOD.replace(r#""library_id": "a12", "workflow": null"#, r#""library_id": null, "workflow": "sprite""#);
    let text: &'static str = Box::leak(text.into_boxed_str());
    let (_, ask) = ask_with(vec![text]);
    let (plan, left) = generate(ask, "s", "u", &Limits::default(), &library(), &workflows()).await.unwrap();
    assert!(left.is_empty(), "{left:?}");
    assert_eq!(plan.asset_tasks[0].library_id.as_deref(), Some("a12"));
    assert!(plan.asset_tasks[0].workflow.is_none());
}

#[test]
fn the_schema_asks_for_both_task_lists() {
    let s = schema();
    let req: Vec<&str> = s["required"].as_array().unwrap().iter().map(|v| v.as_str().unwrap()).collect();
    assert_eq!(req, vec!["title", "goal", "code_tasks", "asset_tasks"]);
    let asset = &s["properties"]["asset_tasks"]["items"];
    for f in ["key", "title", "kind", "tags", "library_id", "workflow", "params", "depends_on", "needed_by"] {
        assert!(asset["properties"][f].is_object(), "{f}");
    }
    assert!(s["properties"]["code_tasks"]["items"]["properties"]["done_when"].is_object());
}
