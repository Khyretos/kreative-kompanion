/// A model answer for a small platformer, all rules kept.
const GOOD: &str = r#"{
  "title": "Tiny platformer",
  "goal": "A knight jumps over pits and collects coins.",
  "code_tasks": [
    {"key": "player", "title": "Player movement", "goal": "The knight runs and jumps.", "steps": ["Add input", "Add gravity"], "done_when": "A test shows the knight lands after a jump", "files": ["src/player.rs"], "lines": 80, "depends_on": []},
    {"key": "coins", "title": "Coins", "goal": "Coins add to the score.", "steps": ["Spawn coins"], "done_when": "A test shows the score rises on pickup", "files": ["src/coins.rs"], "lines": 60, "depends_on": ["player"]}
  ],
  "asset_tasks": [
    {"key": "hero", "title": "Knight sprite", "kind": "sprite", "tags": ["knight", "idle"], "library_id": "a12", "workflow": null, "params": {}, "depends_on": [], "needed_by": ["player"]},
    {"key": "coin_art", "title": "Coin sprite", "kind": "sprite", "tags": ["coin"], "library_id": null, "workflow": "sprite", "params": {"prompt": "a gold coin", "steps": 30, "size": "square"}, "depends_on": [], "needed_by": ["coins"]}
  ]
}"#;

/// GOOD with the coin generated by an audio workflow: wrong output only (its params fit that workflow).
fn bad_answer() -> &'static str {
    let text = GOOD.replace(r#""workflow": "sprite", "params": {"prompt": "a gold coin", "steps": 30, "size": "square"}"#, r#""workflow": "moss-sfx", "params": {"prompt": "a gold coin"}"#);
    assert_ne!(text, GOOD);
    Box::leak(text.into_boxed_str())
}

fn good() -> GamePlan {
    parse(GOOD).expect("the recorded answer parses")
}

fn kinds(found: &[crate::planner::Issue]) -> Vec<String> {
    found.iter().map(|i| i.kind.clone()).collect()
}

fn with_asset(f: impl FnOnce(&mut AssetTask)) -> GamePlan {
    let mut p = good();
    f(&mut p.asset_tasks[1]);
    p
}

